-- Local development only. Production passwords belong in a secret manager.
CREATE ROLE pos_app LOGIN PASSWORD 'local-development-only' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE pos TO pos_app;
GRANT USAGE ON SCHEMA public TO pos_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pos IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO pos_app;
ALTER DEFAULT PRIVILEGES FOR ROLE pos IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO pos_app;
